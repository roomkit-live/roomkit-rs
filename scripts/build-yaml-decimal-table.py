"""Generate the decimal digits accepted by Python's numeric constructors.

Run with the Python used for the served YAML corpus; the generated table is
Unicode data under the repository's Unicode License V3 notice.
"""

from __future__ import annotations

import unicodedata

zeroes = [code for code in range(0x110000) if unicodedata.decimal(chr(code), None) == 0]
print(f"//! Python numeric-constructor decimal digits, Unicode {unicodedata.unidata_version}.")
print("//! Generated by scripts/build-yaml-decimal-table.py; Unicode License V3.")
print("//! Converts decimal digits for numeric constructors, without resolving input types.")
print(f"const ZEROES: [u32; {len(zeroes)}] = [")
for start in range(0, len(zeroes), 8):
    print("    " + ", ".join(f"0x{code:04X}" for code in zeroes[start:start + 8]) + ",")
print(
    """ ];

pub(crate) fn ascii(text: &str) -> String {
    text.chars().map(|character| {
        let code = u32::from(character);
        let after = ZEROES.partition_point(|zero| *zero <= code);
        after.checked_sub(1).and_then(|index| ZEROES.get(index))
            .and_then(|zero| char::from_digit(code - zero, 10))
            .unwrap_or(character)
    }).collect()
}
"""
)
